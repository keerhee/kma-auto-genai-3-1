def day5(out):
    d = out / "Day5"
    rng = random.Random(SEED + 5)
    N = 25
    times = [f"2026-09-15 {8 + (k * 20) // 60:02d}:{(k * 20) % 60:02d}" for k in range(N)]
    # 설비A — 노이즈형: 평소 1.0 근처, 12~16번째에 덱 예시 [1.0,1.1,0.9,3.5,1.0]
    vibA = [round(1.0 + rng.uniform(-0.08, 0.08), 2) for _ in range(N)]
    vibA[11:16] = [1.0, 1.1, 0.9, 3.5, 1.0]
    tempA = [round(52 + rng.uniform(-1.2, 1.2), 1) for _ in range(N)]
    presA = [round(120 + rng.uniform(-2.0, 2.0), 1) for _ in range(N)]
    # 설비B — 추세형: 14번째부터 완만한 상승, 마지막 5개가 덱 예시 [1.0,1.3,1.7,2.2,2.9]
    vibB = [round(1.0 + rng.uniform(-0.06, 0.06), 2) for _ in range(N)]
    vibB[13:20] = [1.04, 1.06, 1.05, 1.08, 1.10, 1.12, 1.09]  # 14~20번째 — 상승 초입(±2σ로는 안 잡힘)
    vibB[20:25] = [1.0, 1.3, 1.7, 2.2, 2.9]  # 21~25번째 — 덱 실습과제 2 시퀀스
    tempB = []
    for k in range(N):
        t = 55 + rng.uniform(-1.0, 1.0)
        if k >= 13:
            t += (k - 12) * 0.9  # 베어링 발열로 온도도 같이 오름
        tempB.append(round(t, 1))
    presB = [round(118 + rng.uniform(-2.0, 2.0), 1) for _ in range(N)]

    def flags(vals):
        m, s = st.mean(vals), st.pstdev(vals)
        lo, hi = m - 2 * s, m + 2 * s
        return m, s, lo, hi, [i for i, v in enumerate(vals) if v < lo or v > hi]

    rows = []
    for k in range(N):
        rows.append([times[k], "설비A(프레스 메인모터)", vibA[k], tempA[k], presA[k], GA])
    for k in range(N):
        rows.append([times[k], "설비B(차체 용접로봇 감속기)", vibB[k], tempB[k], presB[k], GA])
    p = d / "Day5_설비센서_50건_가상.csv"
    n = write_csv(p, ["시간", "설비", "진동(mm/s)", "온도(℃)", "압력(bar)", "비고"], rows)
    res = {}
    for name, series in [("설비A 진동", vibA), ("설비A 온도", tempA), ("설비A 압력", presA),
                         ("설비B 진동", vibB), ("설비B 온도", tempB), ("설비B 압력", presB)]:
        m, s, lo, hi, f = flags(series)
        res[name] = (m, s, lo, hi, [(times[i][-5:], series[i]) for i in f])
    # 설비를 섞어 한꺼번에 계산하면 생기는 차이
    m, s, lo, hi, f = flags(vibA + vibB)
    res["진동(두 설비 합쳐 계산 — 잘못된 방식)"] = (m, s, lo, hi, [("A" if i < N else "B", (vibA + vibB)[i]) for i in f])
